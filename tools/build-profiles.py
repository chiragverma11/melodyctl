#!/usr/bin/env python3
"""Build device profiles + coverage docs from the HeyMelody whitelist.

Reads  whitelist.json                  (compatWhiteList, [wl]-derived)
Writes melodyctl/data/profiles.json    (per-device capability subset for the CLI)
Writes docs/devices/coverage.md        (generated support matrix)

Deterministic, stdlib-only, no network.

Run: python3 tools/build-profiles.py
"""
from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "whitelist.json"
PROFILES = ROOT / "melodyctl" / "data" / "profiles.json"
COVERAGE = ROOT / "docs" / "devices" / "coverage.md"

# product id -> human note; only devices we exercised on hardware belong here.
VERIFIED = {"062410": "OPPO Enco Buds (ETI81), this project"}


def modes(entries: list[dict]) -> list[dict]:
    """(modeType, protocolIndex[, childrenMode]) -> normalised list."""
    out = []
    for m in entries or []:
        item = {"mode_type": m.get("modeType"),
                "protocol_index": m.get("protocolIndex")}
        if m.get("childrenMode"):
            item["children"] = modes(m["childrenMode"])
        out.append(item)
    return out


def gestures(entries: list[dict]) -> list[dict] | None:
    """Whitelist gesture slots: action (and sometimes button) + support mask.

    ``support`` is a bitmask over HeyMelody's function presets (see
    ``melodyctl/protocol.py`` PRESETS) - it is what the app offers per slot.
    """
    out = []
    for c in entries or []:
        item = {"action": c.get("action")}
        if c.get("button") is not None:
            item["button"] = c["button"]
        if c.get("support") is not None:
            item["support"] = c["support"]
        if c.get("ear") is not None:
            item["ear"] = c["ear"]
        if c.get("showEar") is not None:
            item["show_ear"] = c["showEar"]
        if c.get("minSelectCount") is not None:
            item["min_select_count"] = c["minSelectCount"]
        mods = c.get("entryStrModify")
        if mods:
            # raw passthrough: the app uses these to override a few labels
            # (keys vary: categoryVersion / targetFunction + summaryVersion)
            item["entry_str_modify"] = mods
        out.append(item)
    return out or None


def profile_for(entry: dict) -> dict:
    f = entry.get("function", {})
    eq_modes = f.get("equalizerMode")
    anc = f.get("noiseReductionMode")
    return {
        "id": entry["id"],
        "name": entry.get("name"),
        "brand": entry.get("brand"),
        "type": entry.get("type"),
        "uuid": entry.get("uuid"),
        "support_spp": bool(entry.get("supportSpp")),
        "min_version": entry.get("minVersion"),
        "caps": {
            "battery": bool(f.get("batteryInfo")),
            "game_mode": bool(f.get("gameMode")),
            "anc": modes(anc) if anc else None,
            "gestures": gestures(f.get("control")),
            "eq": {
                "modes": modes(eq_modes) if eq_modes else [],
                "custom": bool(f.get("customEqualizer")),
                "frequencies": f.get("customEqFrequency") or [],
            } if (eq_modes or f.get("customEqualizer")) else None,
        },
    }


def main() -> int:
    entries = json.loads(SRC.read_text())["compatWhiteList"]
    profiles: dict[str, dict] = {}
    dups = []
    for e in entries:
        pid = e["id"]
        if pid in profiles:
            dups.append(pid)
        profiles[pid] = profile_for(e)

    out = {
        "_comment": "Generated by tools/build-profiles.py from whitelist.json "
                    "(HeyMelody compatWhiteList). Do not edit by hand. [wl]",
        "_verified": VERIFIED,
        "devices": profiles,
    }
    PROFILES.parent.mkdir(parents=True, exist_ok=True)
    PROFILES.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n")

    n = len(profiles)
    spp = sum(1 for p in profiles.values() if p["support_spp"])
    anc = sum(1 for p in profiles.values() if p["caps"]["anc"])
    eqm = sum(1 for p in profiles.values() if p["caps"]["eq"] and p["caps"]["eq"]["modes"])
    custom = sum(1 for p in profiles.values() if p["caps"]["eq"] and p["caps"]["eq"]["custom"])
    game = sum(1 for p in profiles.values() if p["caps"]["game_mode"])
    gest = sum(1 for p in profiles.values() if p["caps"]["gestures"])
    brands = sorted({p["brand"] for p in profiles.values() if p["brand"]})

    lines = [
        "# Device coverage (generated)",
        "",
        "Generated by `tools/build-profiles.py` from `whitelist.json` "
        "(`compatWhiteList`) - regenerate, do not edit. Everything here is "
        "`[wl]`-derived; only rows marked **verified** were exercised on hardware.",
        "",
        f"- whitelist entries: **{n}**" + (f" (duplicates merged: {', '.join(dups)})" if dups else ""),
        f"- SPP transport advertised: **{spp}** (non-SPP: {n - spp})",
        f"- ANC modes (`noiseReductionMode`): **{anc}**",
        f"- EQ modes (`equalizerMode`): **{eqm}** · custom EQ (`customEqualizer`): **{custom}**",
        f"- game mode (`gameMode`): **{game}**",
        f"- gesture tables (`control`): **{gest}**",
        f"- brands: {', '.join(brands)}",
        "",
        "| id | name | brand | SPP | ANC | EQ | custom EQ | game | gestures | status |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for pid, p in sorted(profiles.items(), key=lambda kv: kv[1]["name"] or ""):
        c = p["caps"]
        lines.append(
            f"| `{pid}` | {p['name']} | {p['brand']} | "
            f"{'yes' if p['support_spp'] else 'no'} | "
            f"{'yes' if c['anc'] else '-'} | "
            f"{'yes' if c['eq'] and c['eq']['modes'] else '-'} | "
            f"{'yes' if c['eq'] and c['eq']['custom'] else '-'} | "
            f"{'yes' if c['game_mode'] else '-'} | "
            f"{len(c['gestures']) if c['gestures'] else '-'} | "
            f"{'verified' if pid in VERIFIED else 'untested'} |")
    COVERAGE.write_text("\n".join(lines) + "\n")

    print(f"profiles: {n} devices -> {PROFILES.relative_to(ROOT)}")
    print(f"coverage: {COVERAGE.relative_to(ROOT)}")
    print(f"stats: spp={spp} anc={anc} eq={eqm} custom={custom} game={game} gestures={gest}")
    print(f"brands: {brands}")
    if dups:
        print(f"WARNING duplicate ids: {dups}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
