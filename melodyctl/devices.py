"""Device profiles: whitelist-derived capabilities and write gating.

``data/profiles.json`` is generated by ``tools/build-profiles.py`` from the
decrypted HeyMelody whitelist (85 entries). Only product ids listed under
``_verified`` may be written to without ``--force``; everything else stays
read-only until someone runs ``melodyctl report`` on the real hardware (see
``docs/devices/coverage.md``).
"""
from __future__ import annotations

import json
from pathlib import Path

_DATA = Path(__file__).resolve().parent / "data" / "profiles.json"


def _load() -> dict:
    with _DATA.open(encoding="utf-8") as fh:
        return json.load(fh)


_DB = _load()
PROFILES: dict[str, dict] = _DB["devices"]
VERIFIED: dict[str, str] = _DB["_verified"]


def profile_for(profile_id: str | None) -> dict | None:
    """Whitelist profile for a product id like '062410', or None if unknown."""
    if not profile_id:
        return None
    return PROFILES.get(profile_id.upper())


def is_verified(profile_id: str | None) -> bool:
    """True when we have hardware-verified this product id ourselves."""
    return bool(profile_id) and profile_id.upper() in VERIFIED


def caps_summary(profile: dict) -> list[str]:
    """Short human summary of the capability flags we understand so far."""
    caps = profile.get("caps", {})
    out: list[str] = []
    if caps.get("battery"):
        out.append("battery")
    anc = caps.get("anc")
    if isinstance(anc, list) and anc:
        out.append(f"anc({len(anc)} modes)")
    if caps.get("game_mode"):
        out.append("game-mode")
    eq = caps.get("eq")
    if isinstance(eq, dict):
        modes = eq.get("modes")
        if modes:
            out.append(f"eq({len(modes)} presets)")
        if eq.get("custom"):
            out.append("custom-eq")
    elif isinstance(eq, list) and eq:
        out.append(f"eq({len(eq)} presets)")
    return out


def write_refusal(profile_id: str | None, action: str) -> str | None:
    """Reason a write must not proceed, or None when the profile is verified."""
    if is_verified(profile_id):
        return None
    if profile_id is None:
        who = "this device (no 0x0103 identity reply)"
    else:
        profile = profile_for(profile_id)
        if profile is None:
            who = f"product id {profile_id} (not in the HeyMelody whitelist)"
        else:
            who = f"{profile.get('name', profile_id)} ({profile_id}, untested profile)"
    return (f"{who}: {action} writes are verified only on 062410 "
            f"(OPPO Enco Buds, ETI81).")
